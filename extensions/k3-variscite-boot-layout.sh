# k3-variscite-boot-layout extension:
# This extension produces a partition layout with two partitions for SD cards
#  - boot (vfat) as required by Sitara platforms
#  - root (ext4)
# It aligns with the partition layout for Yocto builds.
#
# It ensures that the U-Boot environment can be stored at an
# unused area in the SD card (in gap between boot and root partition)
#
# Armbian by default wants to store all BSP components in /boot, which would
# include the kernel and the Device Tree files. The /boot partition is too
# small for this.
# As a result, we use a different mount strategy
# <root partition> is mounted at /
# <boot partition> is mounted at /boot/firmware
# Kernel and Device Tree remain in /boot (This is where both the Armbian build
# system and the Variscite U-Boot expects them).
# Bootloader files are available from Linux in /boot/firmware

# Configure the partition layout.
function pre_prepare_partitions__variscite_layout() {
	BOOTFS_TYPE=fat
	ROOTFS_TYPE=ext4
	BOOTSIZE=40
	IMAGE_PARTITION_TABLE=msdos

	BOOT_FS_LABEL=boot
	ROOT_FS_LABEL=root

        # file system must fill partition regardless of alignment
        mkopts[fat]='-a'
}

# Enable custom partitioning
function prepare_image_size__variscite_layout() {
    USE_HOOK_FOR_PARTITION=yes

    # Account for the 3 MiB gap between boot and rootfs.
    if (( OFFSET < 4 )); then
        EXTRA_ROOTFS_MIB_SIZE=$((${EXTRA_ROOTFS_MIB_SIZE:-0} + 4 - OFFSET))
    fi
}

# Create the partition table.
function create_partition_table__variscite_layout() {
	display_alert "Creating Variscite partition table" "${EXTENSION}" "info"

	run_host_command_logged sfdisk "${SDCARD}.raw" <<'SFDISK'
label: dos
unit: sectors

start=2048,  size=81920, type=c, bootable
start=90112,             type=83
SFDISK
}

# Relocate FAT from /boot to /boot/firmware.
# This runs after the filesystems have been mounted,
# but before the rootfs is copied.
# This allows to have the kernel in the root file
# system, using the boot partition only for the
# boot loader
function format_partitions__variscite_split_boot() {
    display_alert "Variscite: relocating boot filesystem" \
		"SDCARD=${SDCARD}, MOUNT=${MOUNT}, LOOP=${LOOP}" "info"

    [[ "${BOOTFS_TYPE:-}" == "fat" ]] ||
        exit_with_error "Expected BOOTFS_TYPE=fat"
    [[ "${ROOTFS_TYPE:-}" == "ext4" ]] ||
        exit_with_error "Expected ROOTFS_TYPE=ext4"
    [[ -n "${bootpart:-}" ]] ||
        exit_with_error "Missing boot partition"

    local boot_device="${LOOP}p${bootpart}"
    local boot_uuid

    boot_uuid="$(blkid -s UUID -o value "$boot_device")"
    [[ -n "$boot_uuid" ]] ||
        exit_with_error "Could not read FAT UUID"

    mountpoint -q "${MOUNT}/boot" ||
        exit_with_error "FAT /boot not mounted"

    umount "${MOUNT}/boot" ||
        exit_with_error "Could not unmount FAT /boot"

    mkdir -p "${MOUNT}/boot/firmware"
    mount "$boot_device" "${MOUNT}/boot/firmware" ||
        exit_with_error "Could not mount FAT at /boot/firmware"

    # Correct the fstab entry generated by Armbian.
    local fstab="${SDCARD}/etc/fstab"
    local temporary_fstab="${fstab}.variscite"

    if ! awk -v bootuuid="UUID=${boot_uuid}" '
        $1 == bootuuid && $2 == "/boot" && $3 == "vfat" {
            $2 = "/boot/firmware"
            changed++
        }
        { print }
        END { if (changed != 1) exit 1 }
    ' "$fstab" > "$temporary_fstab"; then
        rm -f "$temporary_fstab"
        exit_with_error "Could not relocate /boot entry in fstab"
    fi

    mv "$temporary_fstab" "$fstab"

    # The following code is from k3_common -> format_partitions
    #
    # ROM is very particular about partition IDs
    run_host_command_logged sfdisk --part-type ${LOOP} 1 e
}

# The standard K3 writer copies binaries to /boot.
# Relocate them after the writer has finished.
function post_write_uboot_platform__variscite_move_binaries() {
    local file

    for file in tiboot3.bin tispl.bin u-boot.img uEnv.txt; do
        [[ -f "${MOUNT}/boot/${file}" ]] ||
            exit_with_error "Missing U-Boot binary ${file}"

        mv "${MOUNT}/boot/${file}" \
           "${MOUNT}/boot/firmware/${file}"
    done

    # sysfs.itb can be build optionally
    if [[ -f "${MOUNT}/boot/sysfw.itb" ]]; then
        mv "${MOUNT}/boot/sysfw.itb" \
           "${MOUNT}/boot/firmware/sysfw.itb"
    fi
}
